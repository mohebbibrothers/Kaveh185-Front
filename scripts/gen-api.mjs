// تولید تایپ‌ها از کانتِرار OpenAPI بک‌اند — منبعِ حقیقت واحد.
// خروجی کامیت می‌شود تا بیلد به شبکه وابسته نباشد و هر تغییر قرارداد در diff دیده شود.
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const LOCAL = new URL("../src/shared/api/openapi.yaml", import.meta.url);
const OUT = new URL("../src/shared/api/schema.d.ts", import.meta.url);
const check = process.argv.includes("--check");

const src = process.env.SCHEMA_SRC
  ? process.env.SCHEMA_SRC
  : existsSync(LOCAL)
    ? LOCAL.pathname
    : "http://127.0.0.1:8000/api/v1/schema/";

/**
 * هدرِ منبع باید پایدار باشد، وگرنه گیت و CI مسیر مطلق ماشین را می‌بینند و
 * هر اجرا «رانش» کاذب گزارش می‌کند. پس نام فایل، نسبی ذخیره می‌شود.
 */
const srcLabel = process.env.SCHEMA_SRC
  ? src
  : existsSync(LOCAL)
    ? "src/shared/api/openapi.yaml"
    : src;

const tmp = OUT.pathname + ".tmp";
execSync(`npx openapi-typescript "${src}" -o "${tmp}"`, { stdio: "inherit" });

const header = `/* ⚠️ فایل تولیدی — دست نزنید.\n   منبع: ${srcLabel}\n   تولید: pnpm run api:types\n   این فایل کامیت می‌شود تا بیلد به شبکه وابسته نباشد. */\n`;

/**
 * هدرِ خودکار ابزار را نگه می‌داریم.
 *
 * چرا؟ چون openapi-typescript هدرش را فقط وقتی می‌نویسد که فایل مقصد وجود
 * نداشته باشد. اگر ما آن را حذف کنیم، فایل تولیدی با هر اجرا یک‌بار هدر
 * می‌گیرد و یک‌بار نمی‌گیرد → اسکریپت غیرقطعی می‌شود و CI الکی قرمز.
 * راه درست: هدر ابزار دست‌نخورده بماند و هدر ما قبل از آن بیاید.
 */
const body = readFileSync(tmp, "utf8");
const toolHeader =
  "/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n";
const stripped = body.startsWith(toolHeader)
  ? body.slice(toolHeader.length).replace(/^\n/, "")
  : body;
const next = header + toolHeader + "\n" + stripped;

if (check) {
  const cur = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (cur !== next) {
    console.error(
      "✖ drift قرارداد: schema.d.ts با openapi.yaml همگام نیست. `pnpm run api:types` را بزن.",
    );
    process.exit(1);
  }
  console.log("✔ قرارداد API همگام است");
} else {
  writeFileSync(OUT, next);
  console.log("✔ نوشته شد: src/shared/api/schema.d.ts");
}
